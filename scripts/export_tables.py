#!/usr/bin/env python3
"""Build labelled manuscript tables exclusively from newly computed results."""
from pathlib import Path
import json,hashlib
import pandas as pd
from openpyxl.styles import Font,PatternFill
ROOT=Path(__file__).resolve().parents[1]
rows=json.loads((ROOT/'config/table_sources.json').read_text());out=ROOT/'tables';out.mkdir(exist_ok=True)
missing=[r['path'] for r in rows if not (ROOT/r['path']).is_file()]
if missing:raise FileNotFoundError('Compute table dependencies first: '+', '.join(missing))
index=[]
for table in ['S1','S2','S3']:
    selected=[r for r in rows if r['table']==table];records=[]
    for i,r in enumerate(selected,1):
        f=ROOT/r['path'];records.append(dict(table=table,section=f'{table}.{i:02}',sheet=r['sheet'],source=r['path'],sha256=hashlib.sha256(f.read_bytes()).hexdigest()))
    target=out/f'Supplementary_Table_{table}.xlsx';temp=target.with_suffix('.partial.xlsx')
    with pd.ExcelWriter(temp,engine='openpyxl') as writer:
        pd.DataFrame({'description':['Computed from public inputs with the accompanying repository.','Use the Table index for section identifiers, numerical source paths and checksums.','Model rows report sample size, score units/covariates, effect estimates and uncertainty.','Reconstructed specifications and phosphosite selection are described in docs/METHODS.md.','All numerical sheets are generated by the accompanying workflow.']}).to_excel(writer,sheet_name='Read me',index=False)
        pd.DataFrame(records).to_excel(writer,sheet_name='Table index',index=False)
        for r,record in zip(selected,records):
            d=pd.read_csv(ROOT/r['path'])
            if len(d)>1048575:raise ValueError('Excel row limit exceeded: '+r['path'])
            d.to_excel(writer,sheet_name=r['sheet'],index=False);record['rows']=len(d)
        for ws in writer.book:
            ws.freeze_panes='A2';ws.auto_filter.ref=ws.dimensions
            for cell in ws[1]:cell.font=Font(bold=True,color='FFFFFF');cell.fill=PatternFill('solid',fgColor='27313D')
            for cells in ws.iter_cols():
                width=max(len(str(c.value or '')) for c in list(cells)[:80]);ws.column_dimensions[cells[0].column_letter].width=min(55,max(12,width+2))
    temp.replace(target);index.extend(records)
pd.DataFrame(index).to_csv(out/'Table_index.csv',index=False)
(out/'table_sources.json').write_text(json.dumps(index,indent=2)+'\n')
print('Exported S1–S3:',len(index),'labelled scientific tables.')
